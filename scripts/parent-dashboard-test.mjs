import assert from 'node:assert/strict';
import {validate,summary,demoData,dateKey,shift} from '../parent-dashboard/data.mjs';
const now=new Date('2026-11-07T13:00:00Z'),data=validate(demoData(now));
assert.equal(summary(data,7,now).active,6);
assert.equal(summary(data,7,now).seconds,108*60);
assert.equal(summary(data,7,now).streak,5);
assert.equal(summary(data,30,now).rows.length,30);
assert.equal(summary(data,7,new Date('2026-11-10T13:00:00Z')).streak,null);
assert.equal(summary(data,7,new Date('2026-11-10T13:00:00Z')).status('2026-11-09'),'unknown');
assert.equal(summary(data,7,now).status('2026-11-02'),'empty');
assert.equal(summary(data,7,now).status('2026-10-31'),'unknown');
assert.equal(summary(validate({schema:1,days:[],uploadedAt:null}),7,now).active,0);
assert.equal(dateKey(new Date('2026-11-07T16:00:00Z'),'Asia/Chita'),'2026-11-08');
assert.equal(shift('2024-03-01',-1),'2024-02-29');
assert.throws(()=>validate({...data,days:[data.days[0],data.days[0]]}));
assert.throws(()=>validate({...data,days:[{...data.days[0],day:'2026-02-30'}]}));
assert.throws(()=>validate({...data,days:[{...data.days[0],seconds:-1}]}));
assert.throws(()=>validate({...data,days:[{...data.days[0],exercises:{'<img>':4}}]}));
assert.throws(()=>validate({...data,uploadedAt:null}));
assert.throws(()=>validate({...data,timezone:'bad-zone'}));
console.log('PASS: dashboard totals, streak, empty/stale data, timezone, calendar, invalid and duplicate records');
